/// 应用版本的**唯一来源**。
///
/// 以前这个字符串散在 5 个地方(关于页、设置页、备份文件、同步上报的两处),
/// 每次升版本都要挨个改、很容易漏掉某一处 —— 结果就是「关于页显示 3.2.1、
/// 同步上报 3.2.1、APK 的 versionName 却是别的」。以后只改这里。
///
/// 注意 `pubspec.yaml` 里的 `version:` 改不了这个常量(构建系统不共享 Dart 常量),
/// 所以升版本时**两处都要改**:这里 + pubspec。pubspec 的那个还带构建号
/// (形如 `3.2.2+12`),Android 的 versionName/versionCode 取自它。
///
/// 同步协议里 `/sync/status` 与推送载荷都会带上这个版本号,但对端只把它当
/// 信息显示,不做兼容性校验 —— 所以升版本不会导致两端同步失败。
const String kAppVersion = '3.2.3';
